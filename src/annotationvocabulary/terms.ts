import { NAMESPACES, expandCurie } from './namespaces';
import type { KnownPrefix } from './namespaces';

/**
 * How an annotation's value is written into RDF.
 *  - `text`     plain literal, may carry a language tag (rdfs:label, skos:definition, ...)
 *  - `iri`      the value is an IRI reference (dcterms:creator as a URI, prov:wasDerivedFrom)
 *  - `date`     xsd:date typed literal (dcterms:created)
 *  - `plain`    literal that must never carry a language tag (owl:versionInfo)
 */
export type AnnotationValueKind = 'text' | 'iri' | 'date' | 'plain';

export interface AnnotationTerm {
  /** CURIE, e.g. `skos:prefLabel`. Doubles as the term's stable id in the model. */
  readonly curie: string;
  readonly prefix: KnownPrefix;
  readonly label: string;
  readonly kind: AnnotationValueKind;
  readonly hint: string;
}

const term = (
  curie: string,
  label: string,
  kind: AnnotationValueKind,
  hint: string,
): AnnotationTerm => ({
  curie,
  prefix: curie.slice(0, curie.indexOf(':')) as KnownPrefix,
  label,
  kind,
  hint,
});

