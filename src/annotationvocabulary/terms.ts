const TERMS_BY_CURIE = new Map(ANNOTATION_TERMS.map((t) => [t.curie, t]));

export function findAnnotationTerm(curie: string): AnnotationTerm | undefined {
  return TERMS_BY_CURIE.get(curie);
}

export function annotationTermIri(curie: string): string | null {
  return expandCurie(curie);
}

